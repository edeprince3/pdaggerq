"""
the semidefinite program for variational two-electron reduced density matrix theory

the SDP is autogenerated from pdaggerq output and represented in scipy sparse matrix
format:

  - every block is described by a single role string (e.g. E3 = 'xxo': two creators and
    one annihilator). block sectors, packed (i<j<k) bases, signs, and which spin sectors
    couple into one PSD block all follow from that string, so there are no hand-built
    basis maps or per-block accessors.

  - each pdaggerq term is evaluated for all constraint rows at once with numpy, and the
    rows are assembled directly into CSR chunks. there are no python loops over matrix
    elements and no python lists of triplets.

  - only one row is generated per pair of hermitian-conjugate constraints (r <= c within
    a sector, one ordered pair of sectors within a block), so no numerical removal of
    duplicate constraints is needed.

  - a single cavity mode can be included in a truncated photon-number basis |A>,
    A = 0 .. n_photon (Mallory and DePrince, arXiv:2204.00725). photon operators |A><B|
    commute with fermion operators, so a block can be photon-dressed,
    X(r A; c B) = < O_r O_c^dagger |A><B| >, a Gram matrix of the operators O_r |A><0|, and
    every constraint is the fermion one times |A><B|, with constants multiplying the photon
    1-RDM < |A><B| >. this gives the photon extensions of D, Q, G, 3POS, and 4POS.

    T1, T2, and T2' are not Gram matrices: they are positive because the three-body parts of
    < C C^dagger > and < C^dagger C > cancel, which needs the same photon operator in both
    terms. for C = sum x O |A><C'|, the first term carries |A><B| and the second only
    delta_AB |C'><C'|, so the dressed matrix is not positive. a photon operator Y with
    Y Y^dagger = Y^dagger Y keeps the cancellation, so these blocks are photon-diagonal
    instead: one block per photon state A, < {O_r, O_c^dagger} |A><A| >, whose sum over A is
    the T1/T2/T2' of the electrons.
"""
import itertools
import math
import re

import numpy as np
import scipy.sparse as sp

import pdaggerq

# the roles of the operators in a role string
CREATOR, ANNIHILATOR = 'x', 'o'

# the operators that index the rows of each block: 'x' = creator, 'o' = annihilator, with
# creators first. a block element is X(row; col) = < O_row O_col^dagger >. for T1/T2, it
# is the anticommutator { O_row, O_col^dagger }. T2' (T2P) adds a one-body sector to T2:
# with C = B + sum_l y_l a*_l, B = sum x_ijk a*_i a*_j a_k, it is < C C^dagger > + < B^dagger B >,
# i.e. the anticommutator between three-body sectors and < O_row O_col^dagger > otherwise.
# the role string '1' is the identity operator (no fermion operators); with augment_g2, G2's rows
# are ('xo', '1'), so the G2 block of the number-conserving sectors gains rows 1 |A><C|.
ROLES = {'D1': 'x',    'Q1': 'o',
         'D2': 'xx',   'Q2': 'oo',   'G2': 'xo',
         'D3': 'xxx',  'Q3': 'ooo',  'E3': 'xxo',  'F3': 'xoo',
         'T1': 'xxx',  'T2': 'xxo',  'T2P': ('xxo', 'x'),
         'D4': 'xxxx', 'Q4': 'oooo', 'E4': 'xxxo', 'F4': 'xooo', 'G4': 'xxoo'}

ANTICOMMUTATOR = ('T1', 'T2', 'T2P')

# the role string of the identity operator
IDENTITY = '1'

# names of the photon states (A, B) of a constraint, < ... |A><B| >, among its free indices
PHOTON = ['#A', '#B']

def role_strings(t, roles=ROLES):
    """
    the role string(s) of the row operators of a type-t block, with the identity ('1') as the
    empty string (no fermion operators)
    """
    r = roles[t] if isinstance(roles[t], tuple) else (roles[t],)
    return tuple('' if s == IDENTITY else s for s in r)

def parse_rdm_string(s: str):
    """
    Parses strings like 'd_aa(i,k)', 'Q2_abab(i,j,k,l)', or 'D0'.
    Returns (name, list_of_indices).
    """
    s = s.strip()
    if '(' not in s:
        return s, []
    name, rest = s.split('(', 1)
    return name.strip(), [idx.strip() for idx in rest.rstrip(')').split(',') if idx.strip()]

def parity(v):
    """
    sign of the permutation that sorts the columns of v (shape (k, N)); 0 where two are equal
    """
    sign = np.ones(v.shape[1])
    for s, t in itertools.combinations(range(len(v)), 2):
        sign = sign * np.where(v[s] < v[t], 1.0, np.where(v[s] > v[t], -1.0, 0.0))
    return sign

def pdaggerq_terms(products=(), anticommutator=None, spin_labels=None):
    """
    pdaggerq strings for a sum of operator products (or one anticommutator), as RDMs
    """
    pq = pdaggerq.pq_helper('true')
    pq.set_use_rdms(True)
    for coeff, ops in products:
        pq.add_operator_product(coeff, ops)
    if anticommutator is not None:
        pq.add_anticommutator(1.0, *anticommutator)
    pq.simplify()
    terms = pq.strings(spin_labels=spin_labels or {})
    pq.clear()
    return terms

class sector():
    """
    one spin sector of a block, e.g. roles 'xxo' with spins 'aab' (i^ j^ k, i,j alpha, k beta)

    orbital indices in a run of operators with the same role and spin are antisymmetric,
    so the basis is i<j<... within each run (lexicographic), and the packed index is the
    mixed-radix combination of the runs' ranks.
    """

    def __init__(self, roles, spins, nmo):
        self.roles = roles
        self.spins = spins
        self.nmo = nmo

        # (first position, length) of each run of operators with the same role and spin
        self.runs = []
        for _, run in itertools.groupby(zip(roles, spins)):
            L = len(list(run))
            self.runs.append((sum(r[1] for r in self.runs), L))

        # binomial coefficients C(a, b)
        self.binomial = np.array([[math.comb(a, b) for b in range(len(roles) + 1)] for a in range(nmo + 1)])
        self.size = int(np.prod([self.binomial[nmo, L] for _, L in self.runs]))

    def tuples(self):
        """
        orbital indices (size, k) of every basis function, in packed order
        """
        runs = [itertools.combinations(range(self.nmo), L) for _, L in self.runs]
        return np.array([sum(c, ()) for c in itertools.product(*runs)], dtype=np.int64).reshape(self.size, -1)

    def pack(self, v, count=0):
        """
        packed index and sign for orbital indices v (k arrays, in this sector's operator order)

        :param count: number of elements, needed only for the identity sector (k = 0)
        """
        B = self.binomial
        n = self.nmo
        count = len(v[0]) if len(v) else count
        idx = np.zeros(count, dtype=np.int64)
        sign = np.ones(count)
        for a, L in self.runs:
            run = np.stack(v[a:a + L])
            sign = sign * parity(run)
            run = np.sort(run, axis=0)

            # lexicographic rank of the combination run[0] < run[1] < ...
            rank = np.zeros_like(idx)
            prev = np.full_like(idx, -1)
            for t in range(L):
                rank += B[n - prev - 1, L - t] - B[n - run[t], L - t]
                prev = run[t]
            idx = idx * B[n, L] + rank
        return idx, sign

class v2rdm_sdp():

    def __init__(self,
                 nalpha,
                 nbeta,
                 nmo,
                 oei,
                 tei,
                 q1 = False,
                 q2 = False,
                 g2 = True,
                 augment_g2 = False,
                 t1 = False,
                 t2 = False,
                 t2_prime = False,
                 d3 = False,
                 q3 = False,
                 e3 = False,
                 f3 = False,
                 three_pos = False,
                 d4 = False,
                 q4 = False,
                 e4 = False,
                 f4 = False,
                 g4 = False,
                 four_pos = False,
                 constrain_spin = False,
                 spin_resolved_traces = True,
                 n_photon = None,
                 omega = 0.0,
                 photon_coupling = None,
                 photon_linear = 0.0,
                 photon_stationarity = False,
                 symmetrize_constraint_matrices = True,
                 fold_constraint_matrices = False,
                 chunk_size = 2**20):
        """
        SDP problem

        :param nalpha: number of alpha electrons
        :param nbeta:  number of beta electrons
        :param nmo:    number of spatial molecular orbitals
        :param oei:    core Hamiltonian matrix
        :param tei:    two-electron repulsion integrals
        :param q1: do enforce non-negativity of q1 and d1 <-> q1 mapping?
        :param q2: do enforce non-negativity of q2 and d2 <-> q2 mapping?
        :param g2: do enforce non-negativity of g2 and d2 <-> g2 mapping?
        :param augment_g2: do add the identity operator to the rows of g2 (role strings ('xo', '1'))?
                           the alpha-alpha/beta-beta g2 block becomes [[G, D1], [D1^T, 1]], or, with
                           a photon mode, the Gram matrix of a*_i a_j |A><C| and 1 |B><C|, which ties
                           the electron-photon coherences < a*_i a_j |A><B| > to G and the photon
                           1-RDM (optional, default False)
        :param t1: do enforce non-negativity of t1?
        :param t2: do enforce non-negativity of t2?
        :param t2_prime: do enforce non-negativity of t2' = [[T2, omega], [omega^dagger, D1]]?
                         (contains T2, so t2 is not needed with it)
        :param d3: do enforce non-negativity of D3 and D3 -> D2 contraction?
        :param q3/e3/f3: do enforce non-negativity of Q3/E3/F3 (implies d3)?
        :param three_pos: do enforce non-negativity of D3, Q3, E3, F3 and D3 -> D2 contraction?
        :param d4: do enforce non-negativity of D4 and D4 -> D3 contraction (implies d3)?
        :param q4/e4/f4/g4: do enforce non-negativity of Q4/E4/F4/G4 (implies d4)?
        :param four_pos: do enforce non-negativity of D4, Q4, E4, F4, G4 and D4 -> D3 contraction?
        :param constrain_spin: do constrain spin?
        :param spin_resolved_traces: do constrain the trace of each spin block of d2? if not, only
                                     the total trace, < N N > = N^2, is constrained.
                                     without spin constraints or spin-resolved traces, only
                                     N = nalpha + nbeta enters the SDP, and it may be fractional
                                     (optional, default True)
        :param n_photon: maximum photon number of a single cavity mode in the photon-number
                         basis |A>, A = 0 .. n_photon (optional, default None: no photon mode).
                         with a mode, every block is photon-dressed (see photon_pairs)
        :param omega: photon frequency (the Hamiltonian contains omega b^dagger b)
        :param photon_coupling: matrix g (nmo x nmo) of the bilinear term
                                sum_pq g_pq sum_sigma a*_p a_q (b + b^dagger)
        :param photon_linear: coefficient of the purely photonic term (b + b^dagger)
        :param photon_stationarity: do enforce the stationarity condition < [H, b] > = 0? it holds for
                                    any eigenstate of H (not only for N-representable RDMs), so it
                                    ties the photon displacement < b > to the dipole (optional,
                                    default False; needs a photon mode)
        :param symmetrize_constraint_matrices: do symmetrize the constraint matrices in the sdp (optional, default True)
        :param fold_constraint_matrices: do store each off-diagonal pair (i,j), (j,i) once, as the
                                         upper-triangle element with the full coefficient? this halves
                                         A and c, and is exact for symmetric blocks, but a solver
                                         must expect it, as libsdp.bpsdp_jax does
                                         (optional, default False)
        :param chunk_size: number of constraint rows evaluated at once (bounds working memory)

        members:

        A_mat:            constraint matrix (scipy csr), one row per constraint
        b:                the constraint vector
        c:                the objective function vector (one- and two-electron integrals)
        blocks:           names of the primal blocks (e.g. 'd2ab', 'e3aaa')
        block_dimensions: size of each block
        sectors:          for each block, a list of (spins, offset, sector) for its spin sectors
        n_primal:         number of primal variables
        n_dual:           number of constraints
        """

        self.nmo = nmo
        self.nalpha = nalpha
        self.nbeta = nbeta
        self.symmetrize_constraint_matrices = symmetrize_constraint_matrices
        self.fold_constraint_matrices = fold_constraint_matrices
        self.chunk_size = chunk_size

        # photon-number states per block row (1 without a photon mode)
        self.photon = n_photon is not None
        self.d = n_photon + 1 if self.photon else 1

        q3, e3, f3 = q3 or three_pos, e3 or three_pos, f3 or three_pos
        q4, e4, f4, g4 = q4 or four_pos, e4 or four_pos, f4 or four_pos, g4 or four_pos
        d4 = d4 or q4 or e4 or f4 or g4
        d3 = d3 or q3 or e3 or f3 or d4

        # which block types are in the SDP
        enabled = {'D1': True, 'Q1': q1, 'D2': True, 'Q2': q2, 'G2': g2, 'T1': t1, 'T2': t2, 'T2P': t2_prime,
                   'D3': d3, 'Q3': q3, 'E3': e3, 'F3': f3,
                   'D4': d4, 'Q4': q4, 'E4': e4, 'F4': f4, 'G4': g4}
        self.types = [t for t in ROLES if enabled[t]]

        # row operators of each block type
        self.roles = dict(ROLES)
        if augment_g2:
            self.roles['G2'] = (ROLES['G2'], IDENTITY)

        # blocks, sectors, and offsets
        self.build_blocks()

        # one-electron integrals
        self.h = {'h_aa': oei, 'h_bb': oei}

        # antisymmetrized two-electron integrals
        g_aaaa = 0.25 * (np.einsum('ikjl->ijkl', tei) - np.einsum('iljk->ijkl', tei))
        self.g = {'g_aaaa': g_aaaa, 'g_bbbb': g_aaaa, 'g_abab': 0.25 * np.einsum('ikjl->ijkl', tei)}

        # objective function
        self.c = self.energy(omega, photon_coupling, photon_linear)

        # build constraints
        self.A_chunks = []
        self.b_chunks = []

        # trace of the photon 1-RDM
        if self.photon:
            self.photon_trace()

        # stationarity with respect to the photon annihilation operator
        if photon_stationarity:
            assert self.photon, 'photon_stationarity needs a photon mode'
            self.stationarity_b(omega, photon_coupling, photon_linear)

        # trace of d2 by block, or in total
        if spin_resolved_traces:
            self.trace_d2('a', 'a')
            self.trace_d2('a', 'b')
            self.trace_d2('b', 'b')
        else:
            self.total_trace_d2()

        # dk -> d(k-1) contractions
        for k in (2, 3, 4):
            if 'D' + str(k) in self.types:
                self.contract(k, constrain_spin)

        # mappings between each block and the RDMs
        for t in self.types:
            if t[0] != 'D':
                self.mapping(t)

        if constrain_spin :

            # <s^2> = s(s+1) ... assume maximal spin projection
            self.spin_squared(0.5 * (self.nalpha - self.nbeta))

            # <i*j S+> = 0 (and its conjugate <S- j*i> = 0)
            self.maximal_spin_projection()

        # convert problem into sparse matrix format
        self.A_mat = sp.vstack(self.A_chunks, format='csr')
        self.b = np.concatenate(self.b_chunks)
        del self.A_chunks, self.b_chunks

        # clean the SDP by removing 0 = 0 constraints
        self.remove_zero_constraints()

        # number of dual variables
        self.n_dual = len(self.b)

    def build_blocks(self):
        """
        build blocks, spin sectors, and offsets

        a block type's row operators have the role string ROLES[type]. its sectors are the
        distinct spin assignments (spins sorted, alpha first, within each run of equal
        roles). two sectors couple into the same PSD block when their row operators change
        (n_alpha, n_beta) by the same amount.

        with a photon mode, every row of every block also carries a photon-number state A, at
        position (fermion row) * d + A, and block 'd0' holds the photon 1-RDM, < |A><B| >.
        the exception is T1/T2/T2': their three-body parts cancel only between terms with the
        same photon operator, so they are photon-diagonal, one block per photon state A
        (e.g. 't2aaa_0', 't2aaa_1') holding < {O_r, O_c^dagger} |A><A| >.

        members: groups (block name, type) of every block before photon handling, and for
        every block, block_type, block_group (that name, for its sectors), and block_photon
        (its photon state if it is one of a photon-diagonal set, else None)
        """

        n = self.nmo
        self.blocks = []
        self.block_dimensions = []
        self.block_type = {}
        self.block_group = {}
        self.block_photon = {}
        self.groups = []
        self.photon_diagonal = {}
        self.sectors = {}
        self.sector_of = {}

        def add_block(name, dim, t, group, photon_state=None):
            self.blocks.append(name)
            self.block_dimensions.append(dim)
            self.block_type[name] = t
            self.block_group[name] = group
            self.block_photon[name] = photon_state

        for t in self.types:
            groups = {}
            for roles in role_strings(t, self.roles):
                runs = [len(list(g)) for _, g in itertools.groupby(roles)]
                for choice in itertools.product(*[range(L, -1, -1) for L in runs]):
                    spins = ''.join('a' * na + 'b' * (L - na) for na, L in zip(choice, runs))
                    change = tuple(sum((1 if r == CREATOR else -1) for r, s in zip(roles, spins) if s == x) for x in 'ab')
                    groups.setdefault(change, []).append((roles, spins))
            for sector_list in groups.values():
                name = t.lower() + sector_list[0][1]
                off = 0
                self.sectors[name] = []
                for roles, spins in sector_list:
                    sec = sector(roles, spins, n)
                    self.sectors[name].append((spins, off, sec))
                    self.sector_of[(t, spins)] = (name, off, sec)
                    off += sec.size
                self.groups.append((name, t))
                if self.photon and t in ANTICOMMUTATOR:
                    self.photon_diagonal[name] = ['%s_%i' % (name, A) for A in range(self.d)]
                    for A, copy in enumerate(self.photon_diagonal[name]):
                        add_block(copy, off, t, name, A)
                else:
                    add_block(name, off * self.d, t, name)

        if self.photon:
            add_block('d0', self.d, 'D0', 'd0')
            self.sectors['d0'] = []

        self.block_dim = dict(zip(self.blocks, self.block_dimensions))
        self.block_offset = dict(zip(self.blocks, np.cumsum([0] + [d * d for d in self.block_dimensions])))
        self.n_primal = int(sum(d * d for d in self.block_dimensions))

    def pack(self, t, spins, v, count):
        """
        (block, packed index, sign) for the row (or column) half of an element of a type-t
        block with spins `spins` and orbital indices v (arrays). pdaggerq's spin order within
        a run of equal roles need not be ours, so reorder first and keep the sign. (sorting
        on (run of equal roles, spin) only swaps operators with the same role, which
        anticommute.) count is the number of elements (v is empty for the identity row).
        """
        roles = next(r for r in role_strings(t, self.roles) if len(r) == len(spins))
        run = list(itertools.accumulate((int(a != b) for a, b in zip(roles, roles[1:])), initial=0))
        perm = sorted(range(len(spins)), key=lambda p: (run[p], spins[p]))
        name, off, sec = self.sector_of[(t, ''.join(spins[p] for p in perm))]
        idx, sign = sec.pack([v[p] for p in perm], count)
        perm_sign = parity(np.array(perm)[:, None])[0]
        return name, off + idx, sign * perm_sign

    def evaluate(self, terms, free, vals, constants=None, tensors=None):
        """
        evaluate pdaggerq terms for a set of constraints

        :param terms: pdaggerq output (list of strings)
        :param free: names of the indices that label a constraint (e.g. ['i', 'j', 'a', 'b']),
                     ending with the photon states PHOTON = ['#A', '#B']
        :param vals: orbital values of the free indices, shape (number of constraints, len(free))
        :param constants: scalar factors not appearing in RDM blocks (e.g., N in N D1(i,j) = D2(i,p,j,p))
        :param tensors: named tensors that multiply the RDM (e.g., integrals)
        :return A: sparse matrix with one row per constraint
        :return s: the scalar (D0) part of each constraint (zero with a photon mode, where
                   D0 is the photon 1-RDM element < |A><B| >)
        """
        constants = constants or {}
        tensors = tensors or {}
        n = self.nmo
        N = len(vals)
        rows, cols, data = [], [], []
        s = np.zeros(N)

        # photon states of each constraint: every term is the fermion term times |A><B|
        photon_A = vals[:, free.index(PHOTON[0])]
        photon_B = vals[:, free.index(PHOTON[1])]

        for term in terms:
            coeff = float(term[0])
            elements = []
            for e in term[1:]:
                if e in constants:
                    coeff *= constants[e]
                else:
                    elements.append(parse_rdm_string(e))

            # one entry for every constraint and every value of the summed indices
            names = list(dict.fromkeys(x for _, idx in elements for x in idx))
            dummies = [x for x in names if x not in free]
            grid = np.indices((N,) + (n,) * len(dummies)).reshape(1 + len(dummies), -1)
            row = grid[0]
            v = {x: vals[row, free.index(x)] for x in names if x in free}
            v.update(zip(dummies, grid[1:]))

            # deltas and tensor factors multiply the coefficient
            w = np.full(row.size, coeff)
            rdm = None
            for name, idx in elements:
                if name.startswith('d_'):
                    w = w * (v[idx[0]] == v[idx[1]])
                elif name in tensors:
                    w = w * tensors[name][tuple(v[x] for x in idx)]
                elif name.upper() not in ('D0', '1'):
                    rdm = (name, idx)

            # scalars move to the right-hand side, or, with a photon mode, multiply < |A><B| >
            if rdm is None and not self.photon:
                s += np.bincount(row, weights=w, minlength=N)
                continue

            keep = np.nonzero(w)[0]
            if rdm is None:
                block, i, j, si, sj = 'd0', 0, 0, 1.0, 1.0
            else:
                name, idx = rdm
                # e.g. 'D2_abab' (equal halves) or 'T2P_aaa.a' (row and column spins given apart)
                t, spins = name.split('_')
                row_spins, col_spins = spins.split('.') if '.' in spins else (spins[:len(spins) // 2], spins[len(spins) // 2:])
                k = len(row_spins)
                v = [v[x][keep] for x in idx]
                block, i, si = self.pack(t, row_spins, v[:k], keep.size)
                _, j, sj = self.pack(t, col_spins, v[k:], keep.size)

            if block in self.photon_diagonal:
                # the block for this photon state (constraints on these blocks have A = B)
                copies = self.photon_diagonal[block]
                off = np.array([self.block_offset[copy] for copy in copies])[photon_A[row[keep]]]
                dim = self.block_dim[copies[0]]
            else:
                # position of (fermion row, photon state) in the block
                i = i * self.d + photon_A[row[keep]]
                j = j * self.d + photon_B[row[keep]]
                off = self.block_offset[block]
                dim = self.block_dim[block]
            w = w[keep] * si * sj
            if self.fold_constraint_matrices:
                rows.append(row[keep])
                cols.append(off + np.minimum(i, j) * dim + np.maximum(i, j))
                data.append(w)
            elif self.symmetrize_constraint_matrices:
                rows += [row[keep], row[keep]]
                cols += [off + i * dim + j, off + j * dim + i]
                data += [0.5 * w, 0.5 * w]
            else:
                rows.append(row[keep])
                cols.append(off + i * dim + j)
                data.append(w)

        cat = lambda x, dtype: np.concatenate(x) if x else np.zeros(0, dtype=dtype)
        A = sp.csr_matrix((cat(data, float), (cat(rows, np.int64), cat(cols, np.int64))), shape=(N, self.n_primal))
        A.eliminate_zeros()
        return A, s

    def add_constraints(self, terms, free=(), rows=None, target_b=0.0, constants=None):
        """
        add one constraint, target_b = sum of terms, for every row of orbital values of the
        free indices and photon states (rows is an iterable of arrays, one per chunk, whose
        last two columns are the photon states; None for constraints without free indices).
        with a photon mode, each constraint is the fermion one times |A><B|, so target_b
        multiplies the photon 1-RDM element < |A><B| > instead of being a constant.

        :param terms: pdaggerq output (list of strings)
        :param free: names of the fermion indices that label a constraint
        :param rows: chunks of orbital values of the free indices and photon states
        :param target_b: scalar expectation value constant (e.g. 0, Na*Nb, S*(S+1))
        :param constants: additional scalar factors not appearing in RDM blocks
        """
        if self.photon and target_b != 0.0:
            terms = terms + [[repr(-float(target_b)), 'D0']]
            target_b = 0.0
        for vals in (rows if rows is not None else [self.photon_pairs(upper=True)]):
            A, s = self.evaluate(terms, list(free) + PHOTON, vals, constants)
            self.A_chunks.append(A)
            self.b_chunks.append(target_b - s)

    def photon_pairs(self, upper):
        """
        photon states (A, B) of every element of a photon-dressed scalar, or of its upper
        triangle (A <= B) when upper is True
        """
        A, B = np.indices((self.d, self.d)).reshape(2, -1)
        if upper:
            A, B = A[A <= B], B[A <= B]
        return np.stack([A, B], axis=1)

    def pairs(self, row_sector, col_sector, upper, photon_diagonal=False):
        """
        chunks of orbital values (row tuple + column tuple) and photon states (A, B) for every
        element of a sector pair, or for its upper triangle when upper is True (a row is the
        fermion row and photon state together, (r, A) at position r * d + A). with
        photon_diagonal, only the elements with A = B.
        """
        d = self.d
        R, C = row_sector.tuples(), col_sector.tuples()
        step = max(1, self.chunk_size // (len(C) * d * d))
        for r0 in range(0, len(R), step):
            r, A, c, B = np.indices((min(step, len(R) - r0), d, len(C), d)).reshape(4, -1)
            r += r0
            if photon_diagonal:
                r, A, c, B = r[A == B], A[A == B], c[A == B], B[A == B]
            if upper:
                keep = c * d + B >= r * d + A
                r, A, c, B = r[keep], A[keep], c[keep], B[keep]
            yield np.hstack([R[r], C[c], A[:, None], B[:, None]])

    def mapping(self, t):
        """
        pdaggerq autogenerated mappings X(row; col) = < O_row O_col^dagger > between a
        type-t block and the RDMs, for example E3 (roles 'xxo'):

            E3(i,j,k; a,b,c) = < i^ j^ k c^ b a >

        a block is symmetric, so only one ordered pair of sectors and only the upper
        triangle of a diagonal sector pair are needed; the other elements give the same
        constraints (up to sign).

        :param t: the block type (e.g. 'E3')
        """
        op = lambda role, x: ('a*(%s)' if role == CREATOR else 'a(%s)') % x
        flip = lambda role: ANNIHILATOR if role == CREATOR else CREATOR

        for name, block_type in self.groups:
            if block_type != t:
                continue
            secs = self.sectors[name]
            for s, (spins_r, _, sec_r) in enumerate(secs):
                for spins_c, _, sec_c in secs[s:]:
                    row, col = 'ijkl'[:len(spins_r)], 'abcd'[:len(spins_c)]
                    O_row = [op(r, x) for r, x in zip(sec_r.roles, row)]
                    O_col_dagger = [op(flip(r), x) for r, x in reversed(list(zip(sec_c.roles, col)))]
                    labels = dict(zip(row + col, spins_r + spins_c))
                    if t in ANTICOMMUTATOR and len(spins_r) == len(spins_c) == 3:
                        terms = pdaggerq_terms(anticommutator=(O_row, O_col_dagger), spin_labels=labels)
                    elif not O_row + O_col_dagger:
                        # identity row and column: < 1 >, i.e. the photon 1-RDM (or 1)
                        terms = [['+1.0', '1']]
                    else:
                        terms = pdaggerq_terms([(1.0, O_row + O_col_dagger)], spin_labels=labels)
                    lhs = ['-1.0', '%s_%s.%s(%s)' % (t, spins_r, spins_c, ','.join(row + col))]
                    self.add_constraints(terms + [lhs], row + col,
                                         self.pairs(sec_r, sec_c, upper=spins_r == spins_c,
                                                    photon_diagonal=name in self.photon_diagonal))

    def contract(self, k, constrain_spin):
        r"""
        pdaggerq autogenerated contraction constraints Dk -> D(k-1):

            0 = - N < i^ j^ b a > + < \hat{N} i^ j^ b a >     (e.g. k = 3)

        where \hat{N} is the number operator for one spin (constrain_spin) or both spins,
        for the upper triangle of every D(k-1) sector

        :param k: the rank of the larger RDM
        :param constrain_spin: do resolve the number operator by spin?
        """
        row, col = 'ijk'[:k - 1], 'abc'[:k - 1]
        O = ['a*(%s)' % x for x in row] + ['a(%s)' % x for x in reversed(col)]
        number = {'a': self.nalpha, 'b': self.nbeta}

        for name, block_type in self.groups:
            if block_type != 'D%i' % (k - 1):
                continue
            for spins, _, sec in self.sectors[name]:
                labels = dict(zip(row + col, spins + spins))
                if constrain_spin:
                    cases = [((s,), number[s]) for s in 'ab']
                else:
                    cases = [(('a', 'b'), self.nalpha + self.nbeta)]
                for spin_list, N in cases:
                    products = [(-1.0, ['ON'] + O)]
                    for p, s in zip('pq', spin_list):
                        products.append((1.0, ['a*(%s)' % p, 'a(%s)' % p] + O))
                        labels[p] = s
                    terms = pdaggerq_terms(products, spin_labels=labels)
                    self.add_constraints(terms, row + col, self.pairs(sec, sec, upper=True),
                                         constants={'N0': float(N)})

    def trace_d2(self, s1, s2):
        r"""
        pdaggerq autogenerated trace constraint: N^2 = < \hat{N} \hat{N} >

        :param s1: spin on the first number operator
        :param s2: spin on the second number operator
        """
        terms = pdaggerq_terms([(1.0, ['a*(p)', 'a(p)', 'a*(q)', 'a(q)'])], spin_labels={'p': s1, 'q': s2})
        N1 = self.nalpha if s1 == 'a' else self.nbeta
        N2 = self.nalpha if s2 == 'a' else self.nbeta
        self.add_constraints(terms, target_b=N1 * N2)

    def total_trace_d2(self):
        r"""
        pdaggerq autogenerated total trace constraint: N^2 = < \hat{N} \hat{N} >, with
        \hat{N} = \hat{N}_alpha + \hat{N}_beta and N = nalpha + nbeta
        """
        products = [(1.0, ['a*(p_%s)' % s1, 'a(p_%s)' % s1, 'a*(q_%s)' % s2, 'a(q_%s)' % s2])
                    for s1 in 'ab' for s2 in 'ab']
        terms = pdaggerq_terms(products, spin_labels={'p_a': 'a', 'p_b': 'b', 'q_a': 'a', 'q_b': 'b'})
        N = self.nalpha + self.nbeta
        self.add_constraints(self.strip_spin_suffix(terms), target_b=N * N)

    @staticmethod
    def strip_spin_suffix(terms):
        """
        p_a, p_b -> p in pdaggerq strings
        """
        return [[re.sub(r'([a-zA-Z0-9]+)_[ab](?=[,\)])', r'\1', e) for e in term] for term in terms]

    def spin_squared(self, S):
        r"""
        pdaggerq autogenerated S^2 constraint: S(S+1) = <Sz> + <Sz Sz> + < \hat{S}_ \hat{S}+ >

        :param S: the target spin quantum number
        """
        products = [
            # Sz = 0.5 (a*_{p_a}a*_{p_a} - a*_{p_b} a_{p_b})
            ( 0.5, ['a*(p_a)', 'a(p_a)']),
            (-0.5, ['a*(p_b)', 'a(p_b)']),
            # Sz Sz = 0.25 (a*_{p_a}a*_{p_a} - a*_{p_b} a_{p_b})(a*_{q_a}a*_{q_a} - a*_{q_b} a_{q_b})
            ( 0.25, ['a*(p_a)', 'a(p_a)', 'a*(q_a)', 'a(q_a)']),
            (-0.25, ['a*(p_a)', 'a(p_a)', 'a*(q_b)', 'a(q_b)']),
            (-0.25, ['a*(p_b)', 'a(p_b)', 'a*(q_a)', 'a(q_a)']),
            ( 0.25, ['a*(p_b)', 'a(p_b)', 'a*(q_b)', 'a(q_b)']),
            # S_- S_+ = a*_{q_b} a_{q_a} a*_{p_a} a_{p_b}
            ( 1.0, ['a*(q_b)', 'a(q_a)', 'a*(p_a)', 'a(p_b)']),
        ]
        terms = pdaggerq_terms(products, spin_labels={'p_a': 'a', 'p_b': 'b', 'q_a': 'a', 'q_b': 'b'})
        self.add_constraints(self.strip_spin_suffix(terms), target_b=S * (S + 1))

    def maximal_spin_projection(self):
        r"""
        pdaggerq autogenerated maximal spin projection constraints: 0 = < k^l \hat{S}+ >

        the conjugate constraints, 0 = < \hat{S}_ l^k >, are identical on the space of
        symmetric blocks, so they are not added. (with a photon mode, this holds for every
        photon element (A, B), and the conjugates are the (B, A) ones, so all are added.)
        """
        terms = pdaggerq_terms([(1.0, ['a*(k)', 'a(l)', 'a*(p_a)', 'a(p_b)'])],
                               spin_labels={'k': 'b', 'l': 'a', 'p_a': 'a', 'p_b': 'b'})
        AB = self.photon_pairs(upper=False)
        kl, ab = np.indices((self.nmo * self.nmo, len(AB))).reshape(2, -1)
        rows = np.hstack([np.stack([kl // self.nmo, kl % self.nmo], axis=1), AB[ab]])
        self.add_constraints(self.strip_spin_suffix(terms), ['k', 'l'], [rows])

    def photon_trace(self):
        """
        trace of the photon 1-RDM: 1 = sum_A < |A><A| >
        """
        diagonal = np.stack([np.arange(self.d)] * 2, axis=1)
        A, _ = self.evaluate([['+1.0', 'D0']], PHOTON, diagonal)
        self.A_chunks.append(sp.csr_matrix(A.sum(axis=0)))
        self.b_chunks.append(np.ones(1))

    def stationarity_b(self, omega, photon_coupling, photon_linear):
        r"""
        stationarity condition for the photon annihilation operator, which holds for any
        eigenstate of H:

            0 = < [H, b] > = - omega < b > - < G (1 - (n_photon + 1) |n_photon><n_photon|) >

        with G = sum_pq g_pq a*_p a_q + photon_linear, the operator that multiplies (b + b^dagger)
        in H, < b > = sum_A sqrt(A+1) < |A><A+1| >, and [b, b^dagger] for b truncated to photon
        states 0 .. n_photon. (< [H, b^dagger] > is its complex conjugate.)

        :param omega: photon frequency
        :param photon_coupling: matrix g of the bilinear term (or None)
        :param photon_linear: coefficient of (b + b^dagger)
        """
        d = self.d
        up = np.arange(d - 1)
        diagonal = np.stack([np.arange(d)] * 2, axis=1)
        w = np.ones(d)
        w[-1] = -(d - 1)

        # each term is a sum over photon elements (A, B) with a weight: (terms, rows, weights, tensors)
        parts = [([['+1.0', 'D0']], np.stack([up, up + 1], axis=1), -omega * np.sqrt(up + 1), {}),
                 ([['+1.0', 'D0']], diagonal, -photon_linear * w, {})]
        if photon_coupling is not None:
            g = {'h_aa': photon_coupling, 'h_bb': photon_coupling}
            parts.append((pdaggerq_terms([(1.0, ['h'])]), diagonal, -w, g))

        row = np.zeros(self.n_primal)
        for terms, rows, weights, tensors in parts:
            A, _ = self.evaluate(terms, PHOTON, rows, tensors=tensors)
            row += np.asarray(A.T @ weights).ravel()
        self.A_chunks.append(sp.csr_matrix(row))
        self.b_chunks.append(np.zeros(1))

    def energy(self, omega=0.0, photon_coupling=None, photon_linear=0.0):
        """
        pdaggerq autogenerated objective function (Energy = Tr(h * D1) + Tr(g * D2)), plus,
        with a photon mode, < omega b^dagger b + sum_pq g_pq a*_p a_q (b + b^dagger)
        + photon_linear (b + b^dagger) >, with b^dagger = sum_A sqrt(A+1) |A+1><A|

        :param omega: photon frequency
        :param photon_coupling: matrix g of the bilinear term (or None)
        :param photon_linear: coefficient of (b + b^dagger)
        """
        d = self.d

        # each term is a sum over photon elements (A, B) with a weight: (terms, rows, weights, tensors)
        diagonal = np.stack([np.arange(d)] * 2, axis=1)
        parts = [(pdaggerq_terms([(1.0, ['h']), (1.0, ['g'])]), diagonal, np.ones(d), {**self.h, **self.g})]
        if self.photon:
            up = np.arange(d - 1)
            raise_lower = np.concatenate([np.stack([up + 1, up], axis=1), np.stack([up, up + 1], axis=1)])
            sqrt_n = np.sqrt(np.concatenate([up + 1, up + 1]))
            parts.append(([['+1.0', 'D0']], diagonal, omega * np.arange(d), {}))
            parts.append(([['+1.0', 'D0']], raise_lower, photon_linear * sqrt_n, {}))
            if photon_coupling is not None:
                g = {'h_aa': photon_coupling, 'h_bb': photon_coupling}
                parts.append((pdaggerq_terms([(1.0, ['h'])]), raise_lower, sqrt_n, g))

        c = np.zeros(self.n_primal)
        for terms, rows, weights, tensors in parts:
            A, _ = self.evaluate(terms, PHOTON, rows, tensors=tensors)
            c += np.asarray(A.T @ weights).ravel()
        return c

    def remove_zero_constraints(self):
        """
        remove 0 = 0 constraints
        """
        keep = np.nonzero(self.A_mat.getnnz(axis=1) > 0)[0]
        self.A_mat = self.A_mat[keep, :]
        self.b = self.b[keep]

    def get_rdm_blocks(self, x):
        """
        extract rdm/integral blocks from a vector of dimension of primal solution

        :param x: the vector or rdm/integral elements
        """
        return [np.asarray(x[self.block_offset[name]:self.block_offset[name] + d * d]).reshape(d, d)
                for name, d in zip(self.blocks, self.block_dimensions)]

    def write_rdms_hdf5(self, x, filename):
        """
        write the blocks of a primal solution to an HDF5 file, one (dim, dim) dataset per
        block, keyed by block name (e.g. 'd2ab', 'e3aaa')

        :param x: primal solution vector (e.g. the x returned by a bpsdp solve)
        :param filename: path to the HDF5 file to write
        """
        import h5py  # optional dependency, needed only here

        with h5py.File(filename, 'w') as f:
            f.attrs['nmo'] = self.nmo
            f.attrs['nalpha'] = self.nalpha
            f.attrs['nbeta'] = self.nbeta
            f.attrs['block_names'] = np.array(self.blocks, dtype='S')
            for name, block in zip(self.blocks, self.get_rdm_blocks(x)):
                f.create_dataset(name, data=block)
